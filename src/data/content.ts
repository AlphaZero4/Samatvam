export type Person = { name: string; credentials: string; initials: string; href?: string };

function toPerson(line: string): Person {
  const i = line.indexOf(',');
  const name = line.slice(0, i).trim();
  const initials = name
    .replace(/^(Dr|Ms|Mr|Mrs)\s+/, '')
    .split(/\s+/)
    .filter((w) => /^[A-Z]/.test(w))
    .slice(-2)
    .map((w) => w[0])
    .join('');
  return { name, credentials: line.slice(i + 1).trim(), initials };
}

